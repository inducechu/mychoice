CREATE TABLE cities (
                        id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(255) NOT NULL UNIQUE
);

-- уникальные города из вузов; пустые и из пробелов -> 'Не указан'
INSERT INTO cities (name)
SELECT DISTINCT COALESCE(NULLIF(TRIM(city), ''), 'Не указан')
FROM universities;

-- привязываем вузы к городам
ALTER TABLE universities ADD COLUMN city_id BIGINT REFERENCES cities (id);

UPDATE universities u
SET city_id = c.id
    FROM cities c
WHERE c.name = COALESCE(NULLIF(TRIM(u.city), ''), 'Не указан');

ALTER TABLE universities ALTER COLUMN city_id SET NOT NULL;
ALTER TABLE universities DROP COLUMN city;
