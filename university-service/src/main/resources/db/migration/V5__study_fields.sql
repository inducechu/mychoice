-- укрупнённые группы, например 09.00.00 «Информатика и вычислительная техника»
CREATE TABLE study_fields (
      id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code VARCHAR(8)   NOT NULL UNIQUE,
      name VARCHAR(255) NOT NULL
);

ALTER TABLE directions ADD COLUMN field_id BIGINT REFERENCES study_fields (id);
CREATE INDEX idx_directions_field_id ON directions (field_id);
