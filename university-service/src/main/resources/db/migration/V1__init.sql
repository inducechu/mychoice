CREATE TABLE IF NOT EXISTS universities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(255)  NOT NULL UNIQUE,
    name        VARCHAR(255)  NOT NULL,
    city        VARCHAR(255)  NOT NULL,
    description VARCHAR(2000),
    rating      NUMERIC(3, 1) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_universities_rating_desc ON universities (rating DESC);

CREATE TABLE IF NOT EXISTS faculties (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255)  NOT NULL,
    description   VARCHAR(2000),
    rating        NUMERIC(3, 1) NOT NULL,
    university_id BIGINT        NOT NULL REFERENCES universities (id),
    UNIQUE (university_id, name)
);

CREATE TABLE IF NOT EXISTS directions (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS programs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction_id BIGINT        NOT NULL REFERENCES directions (id),
    name         VARCHAR(255)  NOT NULL,
    description  VARCHAR(2000),
    rating       NUMERIC(3, 1) NOT NULL,
    degree       VARCHAR(32)   NOT NULL,
    faculty_id   BIGINT        NOT NULL REFERENCES faculties (id),
    UNIQUE (faculty_id, name)
);

CREATE TABLE IF NOT EXISTS faculty_stats (
    faculty_id                BIGINT        PRIMARY KEY,
    total_program_rating_sum  NUMERIC(6, 2) NOT NULL,
    program_count             BIGINT        NOT NULL
);

CREATE TABLE IF NOT EXISTS university_stats (
    university_id             BIGINT        PRIMARY KEY,
    total_faculty_rating_sum  NUMERIC(6, 2) NOT NULL,
    faculty_count             BIGINT        NOT NULL
);
