ALTER TABLE user_profiles DROP COLUMN IF EXISTS city;

CREATE TABLE affiliations (
      id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_profile_id BIGINT NOT NULL REFERENCES user_profiles (id) ON DELETE CASCADE,
      university_id   BIGINT NOT NULL,
      faculty_id      BIGINT,
      program_id      BIGINT,
      course          SMALLINT CHECK (course BETWEEN 1 AND 6),
      UNIQUE (user_profile_id, university_id, faculty_id, program_id)
);
CREATE INDEX idx_affiliations_user ON affiliations (user_profile_id);
CREATE INDEX idx_affiliations_university ON affiliations (university_id);
